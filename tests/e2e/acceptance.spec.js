import { test, expect } from '@playwright/test'
import { api, credentials, fixture, issueOffer, loginAPI, loginUI, logoutUI, nextOtpStep, otpFor, propertyAPI, registerAccount, unique } from './helpers.js'

// All requests reach the real local H2 fixture: no route interception or API mocks.
test('registro, errores de ingreso y perfil persistente después de cerrar sesión', async ({ page, request }) => {
  const account = credentials()
  await page.goto('/register')
  await page.locator('#firstName').fill(account.firstName)
  await page.locator('#lastName').fill(account.lastName)
  await page.locator('#email').fill(account.email)
  await page.locator('#password').fill(account.password)
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?/)
  await expect(page.getByRole('status').filter({ hasText: 'Cuenta creada' })).toBeVisible()
  await page.locator('#email').fill(account.email)
  await page.locator('#password').fill('Credencial-incorrecta-123!')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Correo o contraseña incorrectos.')
  expect(await page.evaluate(() => sessionStorage.getItem('fidiacorp.session'))).toBeNull()
  const originalToken = await loginUI(page, account)
  let updates = 0
  page.on('request', request => { if (request.method() === 'PUT' && request.url().endsWith('/users/me')) updates++ })
  await page.locator('#lastName').fill(' ')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No se guardaron los cambios')
  expect(updates).toBe(0)
  account.lastName = 'Apellido actualizado'
  account.email = `perfil-${unique()}@example.com`
  await page.locator('#lastName').fill(account.lastName)
  await page.locator('#email').fill(account.email)
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Tu perfil se actualizó correctamente' })).toBeVisible()
  const profile = await api(request, 'get', '/users/me', { token: originalToken })
  expect(profile.email).toBe(account.email)
  expect(profile.lastName).toBe(account.lastName)
  await logoutUI(page)
  await api(request, 'get', '/users/me', { token: originalToken, status: 401 })
  await loginUI(page, account)
  await expect(page.locator('#lastName')).toHaveValue(account.lastName)
})

test('catálogo real: filtros AND, propios, precio exacto, cancelación y eliminación autorizada', async ({ page, request }) => {
  const account = await registerAccount(request)
  const token = await loginUI(page, account)
  const tag = `prueba-${unique()}`
  await page.goto('/realState')
  await page.getByRole('button', { name: 'Registrar inmueble', exact: true }).click()
  await page.locator('#property-title').fill(`Casa ${tag}`)
  await page.locator('#property-address').fill('Dirección integrada, Lima')
  await page.locator('#property-price').fill('9999999999999999.99')
  await page.locator('#property-tags').fill(`${tag}, terraza, estacionamiento`)
  await page.getByRole('button', { name: 'Guardar inmueble', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Inmueble registrado' })).toBeVisible()
  await page.locator('#property-query').fill('Casa')
  await page.locator('#filter-tags').fill(`${tag}, terraza, estacionamiento`)
  await page.getByLabel('Solo mis inmuebles').check()
  await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
  const card = page.locator('.property-card').filter({ hasText: `Casa ${tag}` })
  await expect(card).toBeVisible()
  await expect(card).toContainText('S/ 9,999,999,999,999,999.99')
  const stored = await api(request, 'get', `/properties?mine=true&tags=${tag}&tags=terraza&tags=estacionamiento`, { token })
  expect(stored.totalElements).toBe(1)
  expect(stored.items[0].price).toBe('9999999999999999.99')
  const otherAuth = await loginAPI(request, fixture.otherClient)
  await api(request, 'delete', `/properties/${stored.items[0].id}`, { token: otherAuth.token, status: 403 })
  await card.getByRole('button', { name: `Eliminar Casa ${tag}`, exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  let deletes = 0
  page.on('request', request => { if (request.method() === 'DELETE') deletes++ })
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(deletes).toBe(0)
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: `Eliminar Casa ${tag}`, exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar eliminación', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Inmueble eliminado' })).toBeVisible()
  await expect(card).toHaveCount(0)
  expect(deletes).toBe(1)
  await expect(page.locator('#filter-tags')).toHaveValue(`${tag}, terraza, estacionamiento`)
  await api(request, 'get', `/properties/${stored.items[0].id}`, { token, status: 404 })
})

test('oferta nueva llega por polling y permite leer el aviso y recuperar su cronograma real', async ({ page, request }) => {
  const account = await registerAccount(request)
  const token = await loginUI(page, account)
  await expect(page.locator('.notification-badge')).toHaveText('0')
  const advisor = await loginAPI(request, fixture.realtor)
  const property = await propertyAPI(request, advisor.token)
  const offer = await issueOffer(request, advisor.token, property.id, account.email)
  await expect(page.locator('.notification-badge')).toHaveText('1', { timeout: 20000 })
  await expect(page.getByRole('status').filter({ hasText: 'Tienes nuevas notificaciones' })).toBeVisible()
  await page.goto('/notifications')
  const notice = page.locator('.notification-list > li').filter({ hasText: offer.title })
  await expect(notice).toBeVisible()
  await expect(notice).toContainText('DEMO')
  await notice.getByRole('button', { name: 'Marcar como leída', exact: true }).click()
  await expect(page.locator('.notification-badge')).toHaveText('0')
  const notices = await api(request, 'get', '/notifications', { token })
  expect(notices.unreadCount).toBe(0)
  const repeated = await api(request, 'patch', `/notifications/${notices.items[0].id}/read`, { token })
  expect(repeated.readAt).toBe(notices.items[0].readAt)
  await notice.getByRole('link', { name: 'Consultar oferta', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/offers/${offer.id}$`))
  await expect(page.getByText('No es una aprobación bancaria', { exact: false })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Todavía no hay un cronograma' })).toBeVisible()
  await page.getByRole('button', { name: 'Generar o recuperar cronograma de oferta', exact: true }).click()
  await expect(page.locator('.schedule-table tbody tr')).toHaveCount(240)
  await expect(page.locator('.schedule-table tbody tr').first().locator('td').first()).toHaveText('29/02/2024')
  await expect(page.locator('.schedule-table tbody tr').last()).toContainText('S/ 0.00')
  const persisted = await api(request, 'get', `/offers/${offer.id}/schedule`, { token })
  expect(persisted.schedule).toHaveLength(240)
  expect(persisted.schedule.at(-1).finalBalance).toBe('0.00')
  expect(persisted.schedule[0].dueDate).toBe('2024-02-29')
  const second = await api(request, 'post', `/offers/${offer.id}/schedule`, { token })
  expect(second.quotationId).toBe(persisted.quotationId)
  await page.reload()
  await expect(page.locator('.quotation-id')).toHaveText(persisted.quotationId)
  await api(request, 'delete', `/properties/${property.id}`, { token: advisor.token, status: 204 })
  expect((await api(request, 'get', `/offers/${offer.id}/schedule`, { token })).quotationId).toBe(persisted.quotationId)
})

test('simulación directa, métricas, recuperación y aislamiento de dos destinatarios', async ({ page, request, browser }) => {
  const account = await registerAccount(request)
  const token = await loginUI(page, account)
  await page.goto('/simulations')
  await page.locator('#sim-loanAmount').fill('100000.00')
  await page.locator('#sim-propertyValue').fill('120000.00')
  await page.locator('#sim-termMonths').fill('24')
  await page.locator('#sim-teaPercent').fill('8.123456')
  await page.locator('#sim-startDate').fill('2024-01-31')
  await page.getByText('Opciones avanzadas: gracia, balón, seguros y gastos', { exact: true }).click()
  await page.locator('#sim-discountPercent').fill('0')
  await page.getByRole('button', { name: 'Calcular simulación', exact: true }).click()
  await expect(page.locator('.schedule-table tbody tr')).toHaveCount(24)
  await expect(page.locator('.schedule-table tbody tr').first()).toContainText('29/02/2024')
  const id = await page.locator('.quotation-id').innerText()
  const saved = await api(request, 'get', `/simulations/${id}`, { token })
  expect(saved.metrics.tea).toBe('0.08123456')
  expect(saved.metrics.discountRateUsed).toMatch(/^0(?:\.0+)?$/)
  expect(saved.schedule.at(-1).finalBalance).toBe('0.00')
  await page.reload()
  await page.locator('#simulation-id').fill(id)
  await page.getByRole('button', { name: 'Recuperar cronograma', exact: true }).click()
  await expect(page.locator('.quotation-id')).toHaveText(id)
  const other = await registerAccount(request)
  const otherAuth = await loginAPI(request, other)
  await api(request, 'get', `/simulations/${id}`, { token: otherAuth.token, status: 404 })
  const advisor = await loginAPI(request, fixture.realtor)
  const property = await propertyAPI(request, advisor.token)
  const offer = await issueOffer(request, advisor.token, property.id, account.email, { termMonths: 24 })
  await api(request, 'get', `/offers/${offer.id}`, { token: otherAuth.token, status: 404 })
  const ownedNotices = await api(request, 'get', '/notifications', { token })
  await api(request, 'patch', `/notifications/${ownedNotices.items[0].id}/read`, { token: otherAuth.token, status: 404 })
  const context = await browser.newContext({ baseURL: process.env.E2E_BASE_URL })
  try {
    const otherPage = await context.newPage()
    await loginUI(otherPage, other)
    await otherPage.goto(`/offers/${offer.id}`)
    await expect(otherPage.getByRole('alert')).toContainText('no existe o no está disponible para tu cuenta')
    await otherPage.goto('/simulations')
    await otherPage.locator('#simulation-id').fill(id)
    await otherPage.getByRole('button', { name: 'Recuperar cronograma', exact: true }).click()
    await expect(otherPage.getByRole('alert')).toContainText('no existe o no pertenece a tu cuenta')
    await expect(otherPage.locator('.schedule-table')).toHaveCount(0)
  } finally { await context.close() }
})

test('cerrar una sesión revoca su token y conserva otra sesión del mismo usuario', async ({ page, request }) => {
  const account = await registerAccount(request)
  const token = await loginUI(page, account)
  const parallel = await loginAPI(request, account)
  expect(parallel.token === token).toBe(false)
  await logoutUI(page)
  await api(request, 'get', '/users/me', { token, status: 401 })
  await api(request, 'get', '/users/me', { token: parallel.token })
  await page.goto('/realState')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  expect(await page.evaluate(() => sessionStorage.getItem('fidiacorp.session'))).toBeNull()
})

test('segundo factor real: activar, exigir OTP al ingresar y desactivar con otro código', async ({ page, request }) => {
  test.setTimeout(150000)
  const account = await registerAccount(request)
  await loginUI(page, account)
  await page.locator('#two-factor-password').fill(account.password)
  await page.getByRole('button', { name: 'Generar clave de configuración', exact: true }).click()
  await expect(page.locator('.setup-secret')).toBeVisible()
  const secret = await page.locator('.setup-secret').innerText()
  expect(/^[A-Z2-7]+$/.test(secret)).toBe(true)
  // Avoid generating a code in the final two seconds of its real 30s window.
  if (Date.now() % 30000 > 28000) await nextOtpStep()
  await page.locator('#confirm-otp').fill(otpFor(secret))
  await page.getByRole('button', { name: 'Confirmar activación', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Segundo factor activado.' })).toBeVisible()
  await expect(page.locator('.setup-secret')).toHaveCount(0)
  const stored = await page.evaluate(() => sessionStorage.getItem('fidiacorp.session'))
  expect(stored.includes(secret)).toBe(false)
  await logoutUI(page)
  await page.locator('#email').fill(account.email)
  await page.locator('#password').fill(account.password)
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page.locator('#login-otp')).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('fidiacorp.session'))).toBeNull()
  await nextOtpStep()
  await page.locator('#login-otp').fill(otpFor(secret))
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByRole('status').filter({ hasText: 'Estado: Activado.' })).toBeVisible()
  await nextOtpStep()
  await page.locator('#two-factor-password').fill(account.password)
  await page.locator('#disable-otp').fill(otpFor(secret))
  await page.getByRole('button', { name: 'Desactivar segundo factor', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Segundo factor desactivado.' })).toBeVisible()
})
